
import React, { createContext, useContext, useState, useEffect, ReactNode } from 'react';

export interface DiaryLog {
  id: string;
  time: string;
  title: string;
  detail: string;
  quantity?: number;
  unit?: string;
  cost?: number;
  isAutoGenerated: boolean;
  eudrLogged: boolean;
  actionType?: 'EXPENSE' | 'INCOME' | 'LOG_ONLY';
}

interface DiaryContextType {
  logs: DiaryLog[];
  addLog: (log: DiaryLog) => void;
}

const DiaryContext = createContext<DiaryContextType | undefined>(undefined);

export const useDiary = () => {
  const context = useContext(DiaryContext);
  if (!context) {
    throw new Error('useDiary must be used within a DiaryProvider');
  }
  return context;
};

export const DiaryProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
  const [logs, setLogs] = useState<DiaryLog[]>([
    {
      id: '1',
      time: '08:30',
      title: 'Thăm vườn buổi sáng',
      detail: 'Kiểm tra độ ẩm và sâu bệnh lô 1',
      isAutoGenerated: false,
      eudrLogged: true,
    },
    {
      id: '2',
      time: '10:15',
      title: 'Tưới nước đợt 2',
      detail: 'Tưới nhỏ giọt khu vực xen canh',
      isAutoGenerated: false,
      eudrLogged: true,
    }
  ]);

  const addLog = (log: DiaryLog) => {
    setLogs(prev => [log, ...prev]);
  };

  return (
    <DiaryContext.Provider value={{ logs, addLog }}>
      {children}
    </DiaryContext.Provider>
  );
};
