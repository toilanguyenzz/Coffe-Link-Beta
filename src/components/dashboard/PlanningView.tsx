import React, { useState, useEffect, useRef } from 'react';
import { Mic, Plus, Trash2, Calendar, CheckCircle2, Circle, AlertCircle, Sparkles, X } from 'lucide-react';

interface Task {
  id: number;
  text: string;
  completed: boolean;
  date: string;
  isAutoGenerated?: boolean;
}

interface PlanningViewProps {
  farmingType: 'organic' | 'traditional';
  autoStartVoice?: boolean;
}

const PlanningView: React.FC<PlanningViewProps> = ({ farmingType, autoStartVoice }) => {
  const [tasks, setTasks] = useState<Task[]>([
    { id: 1, text: "Kiểm tra rệp sáp lô 2 phía ven suối", completed: false, date: "Hôm nay", isAutoGenerated: true },
    { id: 2, text: "Chuẩn bị phân bón vi sinh cho đợt tới", completed: true, date: "Hôm qua" }
  ]);
  const [isListening, setIsListening] = useState(false);
  const [transcript, setTranscript] = useState("");
  
  const isOrganic = farmingType === 'organic';
  const themeColor = isOrganic ? 'text-green-600' : 'text-orange-600';
  const bgColor = isOrganic ? 'bg-green-600' : 'bg-orange-600';
  const lightBg = isOrganic ? 'bg-green-50' : 'bg-orange-50';

  const recognitionRef = useRef<any>(null);

  useEffect(() => {
    if (autoStartVoice) {
      handleStartListening();
    }
  }, [autoStartVoice]);

  const handleStartListening = () => {
    if (!('webkitSpeechRecognition' in window)) {
      alert("Trình duyệt không hỗ trợ nhận diện giọng nói.");
      return;
    }

    const SpeechRecognition = (window as any).webkitSpeechRecognition;
    recognitionRef.current = new SpeechRecognition();
    recognitionRef.current.lang = 'vi-VN';
    recognitionRef.current.continuous = false;
    recognitionRef.current.interimResults = true;

    recognitionRef.current.onstart = () => {
      setIsListening(true);
      setTranscript("Đang lắng nghe bác...");
    };

    recognitionRef.current.onresult = (event: any) => {
        let final = "";
        for (let i = event.resultIndex; i < event.results.length; ++i) {
            if (event.results[i].isFinal) {
                final += event.results[i][0].transcript;
                addTask(final);
                setTranscript("");
                setIsListening(false);
            } else {
                setTranscript(event.results[i][0].transcript);
            }
        }
    }

    recognitionRef.current.onend = () => setIsListening(false);
    recognitionRef.current.start();
  };

  const addTask = (text: string) => {
    if (!text.trim()) return;
    const newTask: Task = {
      id: Date.now(),
      text: text.charAt(0).toUpperCase() + text.slice(1),
      completed: false,
      date: "Hôm nay"
    };
    setTasks(prev => [newTask, ...prev]);
  };

  const toggleTask = (id: number) => {
    setTasks(tasks.map(t => t.id === id ? { ...t, completed: !t.completed } : t));
  };

  const deleteTask = (id: number) => {
    setTasks(tasks.filter(t => t.id !== id));
  };

  return (
    <div className="space-y-6 pb-10">
      {/* Dynamic Voice Input Card */}
      <div className={`relative overflow-hidden rounded-[2.5rem] p-8 text-white shadow-2xl transition-all duration-500 ${bgColor}`}>
         {/* Animated background elements */}
         <div className="absolute -right-10 -top-10 h-40 w-40 rounded-full bg-white/10 blur-3xl animate-pulse"></div>
         <div className="absolute -left-10 -bottom-10 h-32 w-32 rounded-full bg-black/10 blur-2xl"></div>

         <div className="relative z-10 flex flex-col items-center text-center">
            <div className="flex h-14 w-14 items-center justify-center rounded-2xl bg-white/20 backdrop-blur-md mb-4 border border-white/30 shadow-inner">
                <Sparkles className="h-7 w-7 text-yellow-200" />
            </div>
            <h2 className="text-2xl font-black tracking-tight">Lập Kế Hoạch AI</h2>
            <p className="mt-2 text-sm font-medium text-white/80">Nói những gì bác định làm, tôi sẽ ghi lại</p>
            
            {isListening ? (
                <div className="mt-8 w-full">
                    <div className="flex items-center justify-center space-x-1 mb-4 h-8">
                        {[1, 2, 3, 4, 5].map(i => (
                            <div key={i} className={`w-1.5 bg-white rounded-full animate-bounce`} style={{ animationDelay: `${i * 0.1}s`, height: `${Math.random() * 20 + 10}px` }}></div>
                        ))}
                    </div>
                    <div className="rounded-2xl bg-black/20 p-4 backdrop-blur-md border border-white/20 min-h-[60px] flex items-center justify-center">
                        <p className="text-lg font-bold italic">"{transcript || "Đang nghe..."}"</p>
                    </div>
                    <button 
                        onClick={() => { recognitionRef.current?.stop(); setIsListening(false); }}
                        className="mt-4 flex mx-auto items-center text-[10px] font-black uppercase tracking-widest bg-red-500/80 px-4 py-2 rounded-full"
                    >
                        <X className="mr-1 h-3 w-3" /> Hủy bỏ
                    </button>
                </div>
            ) : (
                <button 
                    onClick={handleStartListening}
                    className="mt-8 group relative flex w-full items-center justify-center overflow-hidden rounded-2xl bg-white py-4 shadow-xl transition-all active:scale-95"
                >
                    <div className={`absolute inset-0 translate-y-full bg-gray-50 transition-transform group-hover:translate-y-0`}></div>
                    <div className="relative z-10 flex items-center">
                        <Mic className={`mr-2 h-6 w-6 ${themeColor} animate-pulse`} />
                        <span className={`text-sm font-black uppercase tracking-widest ${themeColor}`}>Bắt đầu ghi âm</span>
                    </div>
                </button>
            )}
         </div>
      </div>

      {/* Task List Section */}
      <div className="space-y-4">
        <div className="flex items-center justify-between px-2">
            <h3 className="text-sm font-black uppercase tracking-widest text-gray-400">Công việc hiện tại</h3>
            <span className={`rounded-full ${lightBg} px-3 py-1 text-[10px] font-bold ${themeColor}`}>
                {tasks.filter(t => !t.completed).length} việc mới
            </span>
        </div>

        <div className="space-y-3">
            {tasks.length === 0 ? (
                <div className="rounded-3xl border-2 border-dashed border-gray-200 p-12 text-center">
                    <p className="text-sm font-medium text-gray-400">Bác chưa có kế hoạch nào cho hôm nay.</p>
                </div>
            ) : (
                tasks.map((task) => (
                    <div 
                        key={task.id} 
                        className={`group flex items-center justify-between rounded-3xl bg-white p-5 shadow-[0_8px_30px_rgb(0,0,0,0.04)] border border-gray-100 transition-all hover:shadow-lg ${task.completed ? 'opacity-60' : ''}`}
                    >
                        <div className="flex items-center gap-4 overflow-hidden">
                            <button 
                                onClick={() => toggleTask(task.id)} 
                                className={`flex h-8 w-8 items-center justify-center rounded-xl transition-all ${
                                    task.completed ? 'bg-gray-100' : `${lightBg} shadow-inner`
                                }`}
                            >
                                {task.completed ? (
                                    <CheckCircle2 className="h-5 w-5 text-gray-400" />
                                ) : (
                                    <Circle className={`h-5 w-5 ${themeColor}`} />
                                )}
                            </button>
                            <div className="flex flex-col overflow-hidden">
                                <span className={`text-sm font-bold tracking-tight ${task.completed ? 'text-gray-400 line-through' : 'text-gray-800'}`}>
                                    {task.text}
                                </span>
                                <div className="mt-1 flex items-center gap-2">
                                    <span className="text-[10px] font-bold text-gray-400">{task.date}</span>
                                    {task.isAutoGenerated && (
                                        <span className="flex items-center rounded bg-blue-50 px-1.5 py-0.5 text-[8px] font-black uppercase tracking-tighter text-blue-600">
                                            AI Suggestion
                                        </span>
                                    )}
                                </div>
                            </div>
                        </div>
                        <button 
                            onClick={() => deleteTask(task.id)}
                            className="p-2 text-gray-300 opacity-0 transition-all hover:text-red-500 group-hover:opacity-100"
                        >
                            <Trash2 className="h-5 w-5" />
                        </button>
                    </div>
                ))
            )}
        </div>
      </div>
      
      {/* Smart Alert Suggestion */}
      <div className="rounded-[2rem] bg-gradient-to-br from-blue-500 to-blue-700 p-6 text-white shadow-xl">
        <div className="flex items-start gap-4">
            <div className="flex h-10 w-10 items-center justify-center rounded-xl bg-white/20 backdrop-blur-md">
                <AlertCircle className="h-6 w-6" />
            </div>
            <div>
                <h3 className="text-sm font-black uppercase tracking-wider">Mẹo từ Agri-OS</h3>
                <p className="mt-1 text-xs font-medium text-white/80 leading-relaxed">
                    Độ ẩm vườn đang tăng cao. Bác nên thêm việc <span className="text-yellow-200 font-bold underline">"Kiểm tra nấm lá"</span> để phòng ngừa sớm.
                </p>
                <button 
                    onClick={() => addTask("Kiểm tra nấm lá và rỉ sắt")}
                    className="mt-4 w-full rounded-xl bg-white py-2 text-xs font-black uppercase tracking-widest text-blue-700 shadow-lg active:scale-95 transition-all"
                >
                    Thêm ngay
                </button>
            </div>
        </div>
      </div>
    </div>
  );
};

export default PlanningView;